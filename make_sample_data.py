def write_raw(key, rows, hdr, path, month='2026/10'):
    br, io = key[:2], key[2:]
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append([f'業績彙整表({io})'])
    ws.append([f'查詢條件　{io}單位：{UNIT[br]}　期間：{month}/01~{month}/31'])
    ws.append([])
    ws.append(hdr)
    for i, (sid, stu, code, staff, d, amt) in enumerate(rows, 1):
        ws.append([br, UNIT[br], f'{key}-{i:03d}', sid, stu, code, COURSES[code], staff, d, amt])
    return wb


